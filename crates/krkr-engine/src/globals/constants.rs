/// `imageTagLayerType = %[opaque : %[type:ltOpaque], ...]` from the same
/// reference script: a dictionary keyed by the image `mode` tag names an image
/// converter emits, each entry a dictionary carrying that layer type.
fn install_image_tag_layer_type(runtime: &mut Runtime<KrkrHost>) {
    let table = runtime.alloc_dictionary_object();
    for (key, value) in [
        ("opaque", 1),
        ("rect", 1),
        ("alpha", 2),
        ("transparent", 2),
        ("addalpha", 12),
        ("add", 3),
        ("sub", 4),
        ("mul", 5),
        ("dodge", 8),
        ("darken", 9),
        ("lighten", 10),
        ("screen", 11),
        ("psnormal", 13),
        ("psadd", 14),
        ("pssub", 15),
        ("psmul", 16),
        ("psscreen", 17),
        ("psoverlay", 18),
        ("pshlight", 19),
        ("psslight", 20),
        ("psdodge", 21),
        ("psdodge5", 22),
        ("psburn", 23),
        ("pslighten", 24),
        ("psdarken", 25),
        ("psdiff", 26),
        ("psdiff5", 27),
        ("psexcl", 28),
    ] {
        let entry = runtime.alloc_dictionary_object();
        runtime.set_object_member(entry, "type", Variant::Integer(value));
        runtime.set_object_member(table, key, Variant::Object(entry));
    }
    runtime.set_global_member("imageTagLayerType", Variant::Object(table));
}
